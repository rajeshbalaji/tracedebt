"""Draft an intended-architecture spec from baseline traces.

Teams rarely have a written spec on day one. `tracedebt init` turns a few
windows of traces from a release the team is happy with into a first draft:

  * services that start traces go to the first layer; the rest are layered
    by hop distance from those entry points (1 -> second layer, >= 2 ->
    third layer); datastores go to the last layer;
  * a datastore touched by one service is owned by it; a datastore touched
    by several is given to the heaviest user and listed for review;
  * every service-to-service call seen in at least half of the windows
    becomes a declared dependency; rarer calls are listed for review;
  * producer/consumer spans become `publishes` / `subscribes`.

The draft is a starting point for a human review, not a substitute for it:
bounded contexts are left empty because traces cannot tell intent.
"""
from __future__ import annotations

import math
from collections import deque
from typing import Dict, List, Sequence, Set, Tuple

import yaml

from .graph import WindowGraph
from .spec import DB_PREFIX, TOPIC_PREFIX

LAYERS = ["edge", "api", "domain", "data"]


def draft(graphs: Sequence[WindowGraph], min_share: float = 0.5,
          min_traces: int = 1) -> Tuple[dict, List[str]]:
    need = max(1, math.ceil(min_share * len(graphs)))
    seen: Dict[Tuple[str, str], int] = {}
    calls: Dict[Tuple[str, str], int] = {}
    roots: Dict[str, int] = {}
    for g in graphs:
        for e, st in g.edges.items():
            if st.traces >= min_traces:
                seen[e] = seen.get(e, 0) + 1
                calls[e] = calls.get(e, 0) + st.calls
        for r, n in g.roots.items():
            roots[r] = roots.get(r, 0) + n
    stable = {e for e, n in seen.items() if n >= need}
    rare = sorted(e for e, n in seen.items() if n < need)
    notes: List[str] = []

    services: Set[str] = set()
    for a, b in stable:
        for n in (a, b):
            if not (n.startswith(DB_PREFIX) or n.startswith(TOPIC_PREFIX)):
                services.add(n)
    # entry points: services that start most of their traces themselves
    total_roots = sum(roots.values()) or 1
    entry = {s for s, n in roots.items() if s in services and n / total_roots >= 0.05}
    if not entry and services:
        entry = {max(services, key=lambda s: roots.get(s, 0))}
    adj: Dict[str, List[str]] = {}
    for a, b in stable:
        if b in services and a in services:
            adj.setdefault(a, []).append(b)
    depth = {s: 0 for s in entry}
    q = deque(entry)
    while q:
        v = q.popleft()
        for w in adj.get(v, []):
            if w not in depth:
                depth[w] = depth[v] + 1
                q.append(w)

    spec_services: Dict[str, dict] = {}
    for s in sorted(services):
        d = depth.get(s)
        if d is None:
            notes.append(f"{s}: not reachable from an entry point; layer guessed")
            d = 2
        spec_services[s] = {"layer": LAYERS[min(d, 2)]}

    # datastore ownership
    users: Dict[str, Dict[str, int]] = {}
    for (a, b) in stable:
        if b.startswith(DB_PREFIX) and a in services:
            users.setdefault(b[len(DB_PREFIX):], {})[a] = calls[(a, b)]
    for db, us in sorted(users.items()):
        owner = max(us, key=us.get)
        spec_services[owner].setdefault("owns", []).append(db)
        if len(us) > 1:
            others = ", ".join(sorted(u for u in us if u != owner))
            notes.append(f"{db}: shared with {others}; owner set to {owner} (heaviest user)")

    deps: Dict[str, List[str]] = {}
    for a, b in sorted(stable):
        if a in services and b in services:
            deps.setdefault(a, []).append(b)
        elif a in services and b.startswith(TOPIC_PREFIX):
            spec_services[a].setdefault("publishes", []).append(b[len(TOPIC_PREFIX):])
        elif a.startswith(TOPIC_PREFIX) and b in services:
            spec_services[b].setdefault("subscribes", []).append(a[len(TOPIC_PREFIX):])
    for a, b in rare:
        notes.append(f"seen only occasionally, not declared: {a} -> {b}")
    spec = {"system": "draft", "layers": LAYERS, "allow_layer_skip": False,
            "services": spec_services, "dependencies": deps,
            "ignore": {"services": [], "operations": []}}
    return spec, notes


def to_yaml(spec: dict, notes: List[str]) -> str:
    head = ["# Draft generated by `tracedebt init` from baseline traces.",
            "# Review before use: add bounded contexts (context: ...), confirm",
            "# layers and datastore owners, and remove calls you do not intend."]
    if notes:
        head.append("#")
        head.append("# Review notes:")
        head += [f"#  - {n}" for n in notes[:60]]
        if len(notes) > 60:
            head.append(f"#  ... and {len(notes) - 60} more")
    return "\n".join(head) + "\n" + yaml.safe_dump(spec, sort_keys=False)
